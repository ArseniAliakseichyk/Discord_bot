import discord
import os
import config.settings as config

async def get_rules_embed(client: discord.Client) -> discord.Embed:
    """
    Возвращает стандартизированный Embed для сообщения с правилами.
    Использует только description и Markdown.
    """
    guild = client.get_guild(config.GUILD_ID)
    if not guild:
        try:
            guild = await client.fetch_guild(config.GUILD_ID)
            guild_icon_url = guild.icon.url if guild and guild.icon else None
        except discord.NotFound:
            print(f"Ошибка: Не удалось найти Guild с ID {config.GUILD_ID}")
            guild_icon_url = None
    else:
        guild_icon_url = guild.icon.url if guild and guild.icon else None
    
    description_content = f"""
# 🦩 Welcome to Гача 🦩

> Мы здесь, чтобы получать удовольствие, играть и отдыхать. 
> Мы – **взрослое** комьюнити (__18+__).

> ### ✅ Ознакомься с правилами ниже и жми **«Согласен»**, чтобы войти.
> 📨 Возникли проблемы? Жми **«Связаться с администрацией»**.

## 🏛️ Наши Три Столпа
### Это __нерушимые__ правила. Нарушение = бан.
1.  **АДЕКВАТНОСТЬ:** Мы 18+. Веди себя как взрослый. Без нытья, токсичности и детских истерик. (Разумеется, мы понимаем, что такое юмор. И даже черный 🥰)
2.  **УВАЖЕНИЕ:** Оскорбление семьи или переход на личности = *мгновенный бан* (Если ваш оппонент не против, то вперед). Политические дебаты – окей, но без грязи.
3.  **ЧЕСТНОСТЬ:** `Скама – нет.` Фишинг, вирусы, попытки кражи аккаунтов – это перманентный бан. Без шансов на аппеляцию. Я не шучу. Реально сразу в бан 😇.

## 🗣️ Голос vs. ⌨️ Текст
* **В Голосе:** Ты *почти* свободен. Трэш-ток, шутки, «performance» – всё можно, пока это не нарушает Три Столпа.
* **В Тексте:** __Строгая модерация.__ Никакого спама или флуда. Все команды ботов – в `канале - 🎧bot`.

## 👑 Иерархия Гачи
> **Администрация** (`🤍Император🤍`, `⚔️Лорды🛡️`) – это закон. Не спорь в общем чате, для этого есть тикеты.
> **Продвижение:** Начинаешь как `Гражданин`. Проявляй активность, вливайся в комьюнити и со временем сможешь получить __кастомную роль__, а может и модерку, кто знает 🤭.

## 🎙️ Твой Сетап
* **Микрофон – обязателен.** Мы играем в команде. Никто не хочет слушать твой перфоратор или эхо из 2005-го.
* *Рекомендуем: `HyperX Cloud` или `SteelSeries Arctis`.*

__                                       __
### Жми   `✅ Согласен`   и погнали!
    """
    
    embed = discord.Embed(
        description=description_content,
        color=discord.Color.from_rgb(255, 105, 180)
    )
    
    if guild_icon_url:
        embed.set_thumbnail(url=guild_icon_url)
    
    return embed